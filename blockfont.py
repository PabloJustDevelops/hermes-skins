# Which block glyph fills an ink pixel. Full block for the body, half blocks on
# the vertical halves so 5 rows read as clean 10-row chunky caps.
def _fill(row: int, col: int) -> str:
    return "█"


def render_wordmark(word: str, gap: int = 1) -> list:
    """Render `word` as a list of text lines using block glyphs."""
    word = word.upper()
    for ch in word:
        if ch not in FONT:
            raise KeyError(f"no block glyph for {ch!r} (add it to FONT)")
    out = []
    for j in range(5):
        parts = []
        for ch in word:
            parts.append(FONT[ch][j].replace("1", _fill(j, 0)).replace("0", " "))
            parts.append(" " * gap)
        out.append("".join(parts).rstrip())
    return out


def render_figlet(word: str, gap: int = 1) -> str:
    return "\n".join(render_wordmark(word, gap))
